<?php

namespace App\Services;

class ReportBuilder
{
    private array $investigation;
    private ?array $target;
    private array $queries;
    private array $evidence;

    public function __construct(array $investigation, ?array $target, array $queries = [], array $evidence = [])
    {
        $this->investigation = $investigation;
        $this->target        = $target;
        $this->queries       = $queries;
        $this->evidence      = $evidence;
    }

    /**
     * Build a full text report (HTML formatted for Telegram)
     */
    public function buildTelegramReport(): string
    {
        $report  = "🕵️ <b>NEUROMAP INVESTIGATION REPORT</b>\n";
        $report .= "━━━━━━━━━━━━━━━━━━━━\n\n";

        $report .= "<b>Case:</b> " . htmlspecialchars($this->investigation['title']) . "\n";
        $report .= "<b>ID:</b> #" . $this->investigation['id'] . "\n";
        $report .= "<b>Status:</b> " . strtoupper($this->investigation['status']) . "\n";
        $report .= "<b>Created:</b> " . $this->investigation['created_at'] . "\n\n";

        // Target Information
        $report .= "<b>SUBJECT INFORMATION</b>\n";
        $report .= "━━━━━━━━━━━━━━━━━━━━\n";

        if ($this->target) {
            $report .= $this->line('Full Name', $this->target['full_name']);
            $report .= $this->line('Aliases', $this->target['aliases']);
            $report .= $this->line('Emails', $this->target['emails']);
            $report .= $this->line('Phones', $this->target['phones']);
            $report .= $this->line('Usernames', $this->target['usernames']);
            $report .= $this->line('Locations', $this->target['locations']);
            $report .= $this->line('Organizations', $this->target['organizations']);
            $report .= $this->line('Websites', $this->target['websites']);
        } else {
            $report .= "No subject details available.\n";
        }

        $report .= "\n";

        // Notes
        if (!empty($this->investigation['notes'])) {
            $report .= "<b>INTERNAL NOTES</b>\n";
            $report .= "━━━━━━━━━━━━━━━━━━━━\n";
            $report .= htmlspecialchars($this->investigation['notes']) . "\n\n";
        }

        // Queries Summary
        $report .= "<b>GENERATED QUERIES</b>\n";
        $report .= "━━━━━━━━━━━━━━━━━━━━\n";
        $report .= "Total dorks generated: <b>" . count($this->queries) . "</b>\n\n";

        if (!empty($this->queries)) {
            $report .= "<b>Sample Queries:</b>\n";
            $sample = array_slice($this->queries, 0, 8);
            foreach ($sample as $i => $q) {
                $report .= ($i + 1) . ". <code>" . htmlspecialchars($q['query_string']) . "</code>\n";
            }

            if (count($this->queries) > 8) {
                $report .= "\n... and " . (count($this->queries) - 8) . " more queries.\n";
            }
        }

        $report .= "\n";

        // Evidence
        $report .= "<b>EVIDENCE COLLECTED</b>\n";
        $report .= "━━━━━━━━━━━━━━━━━━━━\n";
        $report .= "Total evidence items: <b>" . count($this->evidence) . "</b>\n";

        if (!empty($this->evidence)) {
            foreach (array_slice($this->evidence, 0, 5) as $ev) {
                $report .= "• " . htmlspecialchars($ev['title'] ?? $ev['url'] ?? 'Evidence item') . "\n";
            }
        }

        $report .= "\n━━━━━━━━━━━━━━━━━━━━\n";
        $report .= "<i>Generated by NEUROMAP • " . date('Y-m-d H:i:s') . "</i>";

        return $report;
    }

    /**
     * Build a plain text version (for saving as file)
     */
    public function buildPlainReport(): string
    {
        $report  = "NEUROMAP INVESTIGATION REPORT\n";
        $report .= str_repeat("=", 50) . "\n\n";

        $report .= "Case: " . $this->investigation['title'] . "\n";
        $report .= "ID: #" . $this->investigation['id'] . "\n";
        $report .= "Status: " . strtoupper($this->investigation['status']) . "\n";
        $report .= "Created: " . $this->investigation['created_at'] . "\n\n";

        $report .= "SUBJECT INFORMATION\n";
        $report .= str_repeat("-", 50) . "\n";

        if ($this->target) {
            $report .= "Full Name: " . ($this->target['full_name'] ?: '—') . "\n";
            $report .= "Aliases: " . ($this->target['aliases'] ?: '—') . "\n";
            $report .= "Emails: " . ($this->target['emails'] ?: '—') . "\n";
            $report .= "Phones: " . ($this->target['phones'] ?: '—') . "\n";
            $report .= "Usernames: " . ($this->target['usernames'] ?: '—') . "\n";
            $report .= "Locations: " . ($this->target['locations'] ?: '—') . "\n";
            $report .= "Organizations: " . ($this->target['organizations'] ?: '—') . "\n";
            $report .= "Websites: " . ($this->target['websites'] ?: '—') . "\n";
        }

        $report .= "\nGENERATED QUERIES: " . count($this->queries) . "\n";
        $report .= "EVIDENCE ITEMS: " . count($this->evidence) . "\n\n";

        if (!empty($this->queries)) {
            $report .= "QUERIES LIST:\n";
            $report .= str_repeat("-", 50) . "\n";
            foreach ($this->queries as $i => $q) {
                $report .= ($i + 1) . ". " . $q['query_string'] . "\n";
            }
        }

        $report .= "\n" . str_repeat("=", 50) . "\n";
        $report .= "Generated by NEUROMAP on " . date('Y-m-d H:i:s') . "\n";

        return $report;
    }

    private function line(string $label, ?string $value): string
    {
        $val = trim($value ?? '');
        if ($val === '') {
            return "";
        }
        return "<b>{$label}:</b> " . htmlspecialchars($val) . "\n";
    }
}
